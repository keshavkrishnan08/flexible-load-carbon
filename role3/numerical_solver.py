"""
Role 3, Comparative-statics solver for the FCL / Bitcoin-mining carbon paper.

Implements the joint-capacity model of Section 4 (eqs 10, 12, 13, 15) and the
no-FCL benchmark (eqs 6, 7, 9). Residual demand is generated by Monte Carlo so
the same code handles any distribution family, uniform, Beta (controls skew
per footnote 6), lognormal, exponential, Pareto, etc.

Conventions
-----------
Residual demand x = D - K_R * eta, where
    D    ~ raw consumer demand on [0, D_bar]
    eta  ~ renewable-yield factor on [0, 1]
CDF F(x; K_R) is therefore P(D - K_R * eta <= x); shifting K_R shifts mass
leftward, matching the paper's "extended CDF" convention.

All optimisations use a fixed Monte Carlo sample (seeded) so the FOCs are
smooth functions of (K_R, K_F, K_M).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Callable, Dict, Tuple

import numpy as np
from scipy.optimize import brentq, minimize_scalar


# ---------------------------------------------------------------------------
# Distribution registry: each entry returns (D_samples, eta_samples)
# Both are arrays of length n_samples; D in [0, D_bar], eta in [0, 1].
# ---------------------------------------------------------------------------
def _sampler_uniform(n, D_bar, rng):
    return rng.uniform(0, D_bar, n), rng.uniform(0, 1, n)


def _sampler_beta(alpha, beta_):
    def f(n, D_bar, rng):
        D = rng.beta(alpha, beta_, n) * D_bar
        eta = rng.uniform(0, 1, n)
        return D, eta
    return f


def _sampler_lognormal(sigma=0.6):
    def f(n, D_bar, rng):
        raw = rng.lognormal(mean=0.0, sigma=sigma, size=n)
        D = np.clip(raw / np.quantile(raw, 0.999) * D_bar, 0, D_bar)
        eta = rng.uniform(0, 1, n)
        return D, eta
    return f


def _sampler_exponential(scale=0.3):
    def f(n, D_bar, rng):
        raw = rng.exponential(scale=scale, size=n)
        D = np.clip(raw * D_bar, 0, D_bar)
        eta = rng.uniform(0, 1, n)
        return D, eta
    return f


def _sampler_pareto(a=2.5):
    def f(n, D_bar, rng):
        raw = (rng.pareto(a, n) + 1.0)
        D = np.clip((raw - 1) / np.quantile(raw - 1, 0.999) * D_bar, 0, D_bar)
        eta = rng.uniform(0, 1, n)
        return D, eta
    return f


DISTRIBUTIONS: Dict[str, Callable] = {
    "uniform":              _sampler_uniform,
    "beta_a05_b3_right":    _sampler_beta(0.5, 3.0),   # heavily right-skewed
    "beta_a2_b5_right":     _sampler_beta(2.0, 5.0),   # mildly right-skewed
    "beta_a2_b2_symmetric": _sampler_beta(2.0, 2.0),   # symmetric
    "beta_a5_b2_left":      _sampler_beta(5.0, 2.0),   # left-skewed
    "lognormal":            _sampler_lognormal(0.6),
    "exponential":          _sampler_exponential(0.3),
    "pareto":               _sampler_pareto(2.5),
}


# ---------------------------------------------------------------------------
# Parameters
# ---------------------------------------------------------------------------
@dataclass
class Params:
    R: float = 80.0          # mining revenue per MWh
    c: float = 30.0          # fossil variable cost per MWh
    p: float = 100.0         # retail price per MWh
    beta: float = 500.0      # blackout penalty per MWh
    C_F: float = 20.0        # fossil capacity cost per MW
    C_R: float = 15.0        # renewable capacity cost per MW
    C_M: float = 10.0        # FCL hardware capacity cost per MW
    D_bar: float = 1.0       # max consumer demand (units)
    n_samples: int = 40_000
    seed: int = 7

    def C_M_bar(self) -> float:
        """Adoption threshold (eq 27)."""
        return (self.R - self.c) * (self.beta + self.p - self.c - self.C_F) / (
            self.beta + self.p - self.c
        )

    def assumption1_ok(self) -> bool:
        return (
            self.R > self.c
            and self.beta + self.p > self.R
            and self.beta + self.p > self.c + self.C_F
            and self.R < self.c + self.C_F + self.C_M  # interior regime
        )


# ---------------------------------------------------------------------------
# Monte Carlo CDF helpers
# ---------------------------------------------------------------------------
def draw(params: Params, dist: str) -> Tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(params.seed)
    return DISTRIBUTIONS[dist](params.n_samples, params.D_bar, rng)


def residual(D: np.ndarray, eta: np.ndarray, K_R: float) -> np.ndarray:
    return D - K_R * eta


def F(x_query: float, D: np.ndarray, eta: np.ndarray, K_R: float) -> float:
    return float(np.mean(residual(D, eta, K_R) <= x_query))


def F_inverse(q: float, D: np.ndarray, eta: np.ndarray, K_R: float) -> float:
    q = min(max(q, 1e-6), 1 - 1e-6)
    return float(np.quantile(residual(D, eta, K_R), q))


# ---------------------------------------------------------------------------
# No-FCL benchmark (eqs 7, 9)
# ---------------------------------------------------------------------------
def solve_no_fcl(params: Params, D: np.ndarray, eta: np.ndarray,
                 K_R_max: float = 5.0):
    target_F = 1 - params.C_F / (params.beta + params.p - params.c)

    def profit_no_fcl(K_R: float):
        K_F = F_inverse(target_F, D, eta, K_R)
        x = residual(D, eta, K_R)
        fossil = np.minimum(np.maximum(x, 0.0), K_F)
        blackout = np.maximum(x - K_F, 0.0)
        served = params.D_bar - blackout  # surrogate; constants drop in comparison
        return -(params.p * served.mean()
                 - params.c * fossil.mean()
                 - (params.beta + params.p) * blackout.mean()
                 - params.C_F * K_F
                 - params.C_R * K_R)

    res = minimize_scalar(profit_no_fcl, bounds=(1e-4, K_R_max), method="bounded",
                          options={"xatol": 1e-4})
    K_R_star = float(res.x)
    K_F_star = F_inverse(target_F, D, eta, K_R_star)
    return K_R_star, K_F_star


# ---------------------------------------------------------------------------
# Joint optimum with FCL (eqs 12, 13, 15)
# ---------------------------------------------------------------------------
def solve_with_fcl(params: Params, D: np.ndarray, eta: np.ndarray,
                   K_R_max: float = 5.0):
    target_F_KF = (params.beta + params.p - params.c - params.C_F - params.C_M) / (
        params.beta + params.p - params.R
    )
    target_F_KFKM = params.C_M / (params.R - params.c)

    def neg_profit(K_R: float):
        K_F = F_inverse(target_F_KF, D, eta, K_R)
        K_F_minus_K_M = F_inverse(target_F_KFKM, D, eta, K_R)
        K_M = max(K_F - K_F_minus_K_M, 0.0)
        x = residual(D, eta, K_R)
        # FCL dispatch d*(x) = min(max(K_F - x, 0), K_M)
        d = np.minimum(np.maximum(K_F - x, 0.0), K_M)
        fossil = np.minimum(np.maximum(x + d, 0.0), K_F)
        blackout = np.maximum(x - K_F, 0.0)
        served = params.D_bar - blackout
        return -(params.p * served.mean()
                 + params.R * d.mean()
                 - params.c * fossil.mean()
                 - (params.beta + params.p) * blackout.mean()
                 - params.C_F * K_F
                 - params.C_R * K_R
                 - params.C_M * K_M)

    res = minimize_scalar(neg_profit, bounds=(1e-4, K_R_max), method="bounded",
                          options={"xatol": 1e-4})
    K_R_star = float(res.x)
    K_F_star = F_inverse(target_F_KF, D, eta, K_R_star)
    K_F_minus_K_M = F_inverse(target_F_KFKM, D, eta, K_R_star)
    K_M_star = max(K_F_star - K_F_minus_K_M, 0.0)
    return K_R_star, K_F_star, K_M_star


# ---------------------------------------------------------------------------
# Outcome computation (profit, blackout, carbon, fossil utilization)
# ---------------------------------------------------------------------------
def outcomes(params: Params, D: np.ndarray, eta: np.ndarray,
             K_R: float, K_F: float, K_M: float):
    x = residual(D, eta, K_R)
    d = np.minimum(np.maximum(K_F - x, 0.0), K_M)
    fossil = np.minimum(np.maximum(x + d, 0.0), K_F)
    blackout_prob = float(np.mean(x > K_F))
    blackout_energy = float(np.maximum(x - K_F, 0.0).mean())
    carbon = params.c * fossil.mean()
    profit = (params.p * (params.D_bar - np.maximum(x - K_F, 0.0)).mean()
              + params.R * d.mean()
              - params.c * fossil.mean()
              - (params.beta + params.p) * blackout_energy
              - params.C_F * K_F
              - params.C_R * K_R
              - params.C_M * K_M)
    fcl_dispatch = float(d.mean())
    return {
        "profit": float(profit),
        "blackout_prob": blackout_prob,
        "carbon": float(carbon),
        "fcl_dispatch": fcl_dispatch,
        "fossil_output": float(fossil.mean()),
    }


# ---------------------------------------------------------------------------
# Case C (Section 5.3): both K_F^(0), K_R^(0) fixed
# ---------------------------------------------------------------------------
def case_c(params: Params, D: np.ndarray, eta: np.ndarray,
           K_R0: float, K_F0: float):
    """Return (K_M*, ΔCarbon) under the short-run regime of Section 5.3."""
    target = params.C_M / (params.R - params.c)
    if F(K_F0, D, eta, K_R0) <= target:
        return 0.0, 0.0
    K_F_minus_K_M = F_inverse(target, D, eta, K_R0)
    K_M_star = max(K_F0 - K_F_minus_K_M, 0.0)
    x = residual(D, eta, K_R0)
    fossil_with = np.minimum(np.maximum(x + np.minimum(np.maximum(K_F0 - x, 0.0),
                                                       K_M_star), 0.0), K_F0)
    fossil_without = np.minimum(np.maximum(x, 0.0), K_F0)
    delta_carbon = params.c * float(fossil_with.mean() - fossil_without.mean())
    return float(K_M_star), float(delta_carbon)